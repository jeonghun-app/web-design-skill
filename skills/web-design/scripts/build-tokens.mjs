#!/usr/bin/env node
// Build design tokens + trend packs into:
//   src/design/tokens.css            Tailwind v4 @theme + mode/trend overrides
//   src/design/fonts.json            font stylesheets: base (+ default trend) eager, other trends on demand
//   src/design/fonts.ts              (framework "next" only) next/font/google faces for every included trend
//   src/design/trends.json           included trend list (for the dev switcher)
//   design/build/figma-variables.json  variables for Figma (per trend, light/dark)
//   design/build/tokens.resolved.json  resolved values (used by check/audit)
//
// Usage: node build-tokens.mjs [--root <project>] [--check]
//   --check  exit 1 if generated files are out of date (for CI)

import path from 'node:path';
import {
  THEME_NAMESPACES, MODES, cssValue, cssVar, flatten, listTrends, loadTrend, overlay,
  parseArgs, projectPaths, readConfig, readJSON, resolveMode, writeIfChanged,
} from './lib/tokens.mjs';
import { toVariable } from './lib/figma.mjs';

const args = parseArgs(process.argv.slice(2));
const root = path.resolve(args.root ?? process.cwd());
const P = projectPaths(root);
const config = readConfig(root);

const base = flatten(readJSON(P.tokens));
const available = listTrends(root).map(loadTrend);
const included = config.include === 'active'
  ? available.filter((t) => t.id === config.trend)
  : available.filter((t) => config.include === 'all' || (Array.isArray(config.include) && config.include.includes(t.id)));

if (config.trend !== 'none' && !available.some((t) => t.id === config.trend)) {
  console.error(`Active trend "${config.trend}" not found. Run: trend.mjs list`);
  process.exit(1);
}
if (config.trend !== 'none' && !included.some((t) => t.id === config.trend)) {
  console.error(`Active trend "${config.trend}" is not in "include" (${JSON.stringify(config.include)}), so its CSS would not ship. Add it or run: trend.mjs apply ${config.trend}`);
  process.exit(1);
}

const HEADER = '/* GENERATED by web-design/scripts/build-tokens.mjs. Do not edit.\n   Edit design/tokens.json or design/trends/<id>/pack.json, then rebuild. */\n';

function declarations(flat, pick, indent = '  ') {
  return Object.entries(flat)
    .filter(([k, t]) => pick(k, t))
    .map(([k, v]) => `${indent}${cssVar(k)}: ${cssValue(v)};`)
    .join('\n');
}

const ns = (k) => k.split('.')[0];
const lightValues = (flat) => Object.fromEntries(Object.entries(flat).map(([k, t]) => [k, t.$value]));
const darkValues = (flat) => Object.fromEntries(
  Object.entries(flat).filter(([, t]) => t.modes?.dark !== undefined).map(([k, t]) => [k, t.modes.dark]),
);

let css = HEADER;
css += '\n@theme {\n  --color-*: initial;\n';
css += declarations(lightValues(base), (k) => THEME_NAMESPACES.has(ns(k)));
css += '\n}\n\n:root {\n';
css += declarations(lightValues(base), (k) => !THEME_NAMESPACES.has(ns(k)));
css += '\n  color-scheme: light;\n}\n';
// Custom properties that reference other properties are computed where they are
// declared, so derived tokens are re-declared on every element that sets its own
// data-trend or data-theme. That lets a subtree preview another trend, another theme,
// or both. Specificity plan (later wins on ties):
//   0,0,0  :where(...)                 derived formulas, light then dark
//   0,1,0  [data-theme=light|dark]     base mode values
//   0,1,0  [data-trend=x]              trend light values
//   0,2,0+ trend x combined with a theme on the same element or an ancestor/descendant
const derivedOf = (vals) => Object.fromEntries(Object.entries(vals).filter(([, v]) => /\{|var\(/.test(String(v))));
const baseDarkRaw = Object.fromEntries(Object.entries(base).map(([k, t]) => [k, t.modes?.dark ?? t.$value]));
css += '\n:where([data-trend], [data-theme]) {\n';
css += declarations(derivedOf(lightValues(base)), () => true);
css += '\n}\n\n:where([data-theme="dark"], [data-theme="dark"] [data-trend]:not([data-theme="light"])) {\n';
css += declarations(derivedOf(baseDarkRaw), () => true);
css += '\n}\n\n[data-theme="light"] {\n';
css += declarations(Object.fromEntries(Object.keys(darkValues(base)).map((k) => [k, base[k].$value])), () => true);
css += '\n  color-scheme: light;\n}\n\n[data-theme="dark"] {\n';
css += declarations(darkValues(base), () => true);
css += '\n  color-scheme: dark;\n}\n';

const resolved = { base: {} };
const figma = { generatedAt: null, collection: 'web-design', modes: MODES, trends: {} };
for (const mode of MODES) resolved.base[mode] = resolveMode(base, mode);
figma.trends.none = toFigma(base);

// Variants exist for every available trend, so components that use them still
// compile when a locked build ships only the active trend.
css += '\n' + available.map((t) => `@custom-variant trend-${t.id} (&:where([data-trend="${t.id}"], [data-trend="${t.id}"] *));`).join('\n') + '\n';

for (const t of included) {
  const over = flatten(t.pack.tokens ?? {});
  const merged = overlay(base, over);
  const sel = `[data-trend="${t.id}"]`;
  css += `\n/* trend: ${t.id} (${t.pack.stage ?? 'unknown'}, reviewed ${t.pack.reviewed ?? '?'}) */\n`;
  const overLight = Object.fromEntries(Object.keys(over).map((k) => [k, merged[k].$value]));
  const overDark = Object.fromEntries(Object.keys(over).map((k) => [k, merged[k].modes.dark ?? merged[k].$value]));
  css += `${sel} {\n${declarations(overLight, () => true)}\n}\n`;
  css += `[data-theme="light"]${sel},\n${sel} [data-theme="light"] {\n${declarations(overLight, () => true)}\n}\n`;
  css += `[data-theme="dark"]${sel},\n[data-theme="dark"] ${sel}:not([data-theme="light"]),\n${sel} [data-theme="dark"] {\n${declarations(overDark, () => true)}\n}\n`;
  if (t.css.trim()) {
    if (!t.css.includes(sel)) console.warn(`warn: ${t.id}/pack.css should scope every rule under ${sel}`);
    // Unlayered on purpose: it must win over Tailwind's utilities layer.
    css += `${t.css.trim()}\n`;
  }
  resolved[t.id] = Object.fromEntries(MODES.map((m) => [m, resolveMode(merged, m)]));
  figma.trends[t.id] = toFigma(merged);
}

// Fonts are not @imported from CSS: that chains main CSS -> font CSS -> font files and blocks
// first paint on fonts of trends that aren't even active. The Vite plugin links `eager` from
// the HTML head (parallel with the main CSS); src/lib/trend-fonts.ts loads a trend's extra
// fonts only when that trend is switched on (web-quality.md PF-16).
const hrefs = (fonts) => (fonts ?? []).map((f) => f.href).filter(Boolean);
const active = included.find((t) => t.id === config.trend);
const eagerFonts = [...(config.fonts ?? []), ...(active?.pack.fonts ?? [])];
const allFonts = [...eagerFonts, ...included.flatMap((t) => t.pack.fonts ?? [])];

// Next.js: Google fonts go through next/font (self-hosted at build time, size-adjusted
// fallbacks). next/font renames the family, so token font stacks reference it as
// var(--nf-<slug>, "<Family>"), which falls back to the literal name if the face is absent.
const isNext = config.framework === 'next';
const isGoogle = (f) => /^https:\/\/fonts\.googleapis\.com\/css2\?/.test(f.href ?? '');
const nextFaces = isNext ? [...new Map(allFonts.filter(isGoogle).map((f) => [f.family, f])).values()] : [];
const slug = (family) => family.toLowerCase().replace(/[^a-z0-9]+/g, '-');
if (nextFaces.length) {
  const families = nextFaces.map((f) => f.family).sort((a, b) => b.length - a.length);
  css = css.split('\n').map((line) => {
    if (!/^\s*--font-[\w-]+:/.test(line)) return line;
    const [prop, value] = [line.slice(0, line.indexOf(':') + 1), line.slice(line.indexOf(':') + 1)];
    return prop + value.split(',').map((part) => {
      const name = part.trim().replace(/;$/, '').replace(/^"|"$/g, '');
      const fam = families.find((f) => f === name);
      return fam ? part.replace(part.trim().replace(/;$/, ''), `var(--nf-${slug(fam)}, "${fam}")`) : part;
    }).join(',');
  }).join('\n');
}

// Fonts are not @imported from CSS: that chains main CSS -> font CSS -> font files and blocks
// first paint on fonts of trends that aren't even active. The Vite plugin links `eager` from
// the HTML head (parallel with the main CSS); src/lib/trend-fonts.ts loads a trend's extra
// fonts only when that trend is switched on (web-quality.md PF-16). Under Next, next/font
// faces are excluded here: their CSS ships with the app and files load only when used.
const linked = (fonts) => hrefs((fonts ?? []).filter((f) => !(isNext && isGoogle(f))));
const eager = [...new Set(linked(eagerFonts))];
const fontsJson = {
  eager,
  trends: Object.fromEntries(included.map((t) => [t.id, linked(t.pack.fonts).filter((h) => !eager.includes(h))]).filter(([, h]) => h.length)),
};

// next/font options from the css2 URL: family=Name:ital,opsz,wght@<values>
function nextFontCall(f) {
  const spec = decodeURIComponent(new URL(f.href).searchParams.get('family') ?? f.family);
  const [, axesPart = '', values = ''] = spec.match(/^[^:]+(?::([^@]+)@(.+))?$/) ?? [];
  const axes = axesPart ? axesPart.split(',') : [];
  const tuples = values ? values.split(';').map((v) => v.split(',')) : [];
  const col = (name) => tuples.map((t) => t[axes.indexOf(name)]);
  const opts = { subsets: ['latin'], display: 'swap', variable: `--nf-${slug(f.family)}`, preload: eagerFonts.some((e) => e.family === f.family) };
  const wght = axes.includes('wght') ? [...new Set(col('wght'))] : [];
  if (wght.length && !wght.some((w) => w.includes('..'))) opts.weight = wght;
  if (axes.includes('ital')) opts.style = ['normal', 'italic'];
  const extra = axes.filter((a) => !['wght', 'ital'].includes(a));
  if (extra.length) opts.axes = extra;
  const id = f.family.replace(/\s+/g, '_');
  return { id, name: id.charAt(0).toLowerCase() + id.slice(1).replace(/_(\w)/g, (_, c) => c.toUpperCase()), opts };
}
const tsValue = (v) => (Array.isArray(v) ? `[${v.map(tsValue).join(', ')}]` : typeof v === 'string' ? `'${v}'` : String(v));
const tsObject = (o) => `{ ${Object.entries(o).map(([k, v]) => `${k}: ${tsValue(v)}`).join(', ')} }`;
const fontsTs = isNext
  ? (() => {
      const calls = nextFaces.map(nextFontCall);
      return `// GENERATED by web-design/scripts/build-tokens.mjs. Do not edit.\n// next/font faces for the included trends; only the base and default-trend faces preload.\n`
        + (calls.length ? `import { ${calls.map((c) => c.id).join(', ')} } from 'next/font/google'\n\n` : '\n')
        + calls.map((c) => `export const ${c.name} = ${c.id}(${tsObject(c.opts)})`).join('\n')
        + `\n\n/** Class names that define the --nf-* variables; put them on <html>. */\nexport const fontVariables = [${calls.map((c) => `${c.name}.variable`).join(', ')}].join(' ')\n`;
    })()
  : null;

function toFigma(flat) {
  const res = Object.fromEntries(MODES.map((m) => [m, resolveMode(flat, m)]));
  return Object.entries(flat).map(([k, t]) => toVariable(k, t, res)).filter(Boolean);
}

const outputs = [
  [P.cssOut, css],
  [path.join(path.dirname(P.cssOut), 'fonts.json'), JSON.stringify(fontsJson, null, 2) + '\n'],
  ...(fontsTs ? [[path.join(path.dirname(P.cssOut), 'fonts.ts'), fontsTs]] : []),
  [path.join(path.dirname(P.cssOut), 'trends.json'), JSON.stringify(included.map((t) => ({ id: t.id, name: t.pack.name, stage: t.pack.stage, summary: t.pack.summary, preferTheme: t.pack.preferTheme })), null, 2) + '\n'],
  [P.figmaOut, JSON.stringify(figma, null, 2) + '\n'],
  [P.resolvedOut, JSON.stringify(resolved, null, 2) + '\n'],
];

if (args.check) {
  const fs = await import('node:fs');
  const stale = outputs.filter(([f, c]) => !fs.existsSync(f) || fs.readFileSync(f, 'utf8') !== c);
  if (stale.length) {
    console.error('Generated token files are stale:\n' + stale.map(([f]) => '  ' + path.relative(root, f)).join('\n'));
    process.exit(1);
  }
  console.log('tokens up to date');
} else {
  for (const [f, c] of outputs) if (writeIfChanged(f, c)) console.log('wrote', path.relative(root, f));
  console.log(`trends included: ${included.map((t) => t.id).join(', ') || '(none)'}; active: ${config.trend}`);
}
