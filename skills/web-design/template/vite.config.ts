import { readFileSync } from 'node:fs'
import { fileURLToPath, URL } from 'node:url'
import tailwindcss from '@tailwindcss/vite'
import react from '@vitejs/plugin-react'
import { defineConfig, loadEnv, type Plugin, type Rollup } from 'vite'

// Crawlable paths for sitemap.xml. Hash routes (#/app, #/system) are one document to a crawler,
// so only real paths belong here.
const SITEMAP_PATHS = ['/']

// robots.txt and sitemap.xml need the absolute origin, so they are generated from VITE_SITE_URL
// instead of living in public/ (web-quality.md SE-20).
function seoFiles(): Plugin {
  let site = ''
  const robots = () => `User-agent: *\nAllow: /\n\nSitemap: ${site}/sitemap.xml\n`
  const sitemap = () =>
    `<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n${SITEMAP_PATHS.map((p) => `  <url><loc>${site}${p}</loc></url>`).join('\n')}\n</urlset>\n`
  return {
    name: 'seo-files',
    configResolved(config) {
      site = (loadEnv(config.mode, config.root, 'VITE_').VITE_SITE_URL ?? '').replace(/\/$/, '')
      if (!/^https?:\/\//.test(site)) throw new Error('Set VITE_SITE_URL in .env to the absolute site origin, e.g. https://example.com')
    },
    configureServer(server) {
      server.middlewares.use((req, res, next) => {
        if (req.url === '/robots.txt') { res.setHeader('Content-Type', 'text/plain'); res.end(robots()); return }
        if (req.url === '/sitemap.xml') { res.setHeader('Content-Type', 'application/xml'); res.end(sitemap()); return }
        next()
      })
    },
    generateBundle() {
      this.emitFile({ type: 'asset', fileName: 'robots.txt', source: robots() })
      this.emitFile({ type: 'asset', fileName: 'sitemap.xml', source: sitemap() })
    },
  }
}

// Font stylesheets from src/design/fonts.json (generated by build-tokens) are linked from the head
// so they download in parallel with the main CSS instead of after it (web-quality.md PF-16).
function designFonts(): Plugin {
  return {
    name: 'design-fonts',
    transformIndexHtml(html) {
      const { eager } = JSON.parse(readFileSync(new URL('./src/design/fonts.json', import.meta.url), 'utf8')) as { eager: string[] }
      // Font CSS is fetched without CORS, font files with it, so the file origin gets `crossorigin`.
      const pre = new Map<string, boolean>()
      for (const href of eager) {
        const u = new URL(href)
        if (u.hostname === 'fonts.googleapis.com') { pre.set(u.origin, false); pre.set('https://fonts.gstatic.com', true) }
        else pre.set(u.origin, true)
      }
      const tags = [
        ...[...pre].map(([href, cors]) => `<link rel="preconnect" href="${href}"${cors ? ' crossorigin' : ''} />`),
        ...eager.map((href) => `<link rel="stylesheet" href="${href.replaceAll('&', '&amp;')}" />`),
      ]
      return afterCharset(html, tags.join('\n    '))
    },
  }
}

// Injected tags go right after <meta charset> (which must stay in the first 1024 bytes) and
// before the entry script and stylesheet, so they start downloading first.
function afterCharset(html: string, tags: string) {
  return html.replace(/(<meta charset[^>]*>)/i, `$1\n    ${tags}`)
}

// Lazy routes and the module that renders them. Keep in sync with App.tsx.
const ROUTES: Record<string, string> = { '/app': 'src/screens/app-demo.tsx', '/system': 'src/screens/system.tsx' }

// A lazy route normally waits for the entry chunk to download and run before its own chunk is
// requested: a waterfall that costs a full round trip on mobile. This injects a tiny inline
// script that reads the hash on first load and modulepreloads that route's chunks in parallel
// with the entry (web-quality.md PF-05).
function routePreload(): Plugin {
  let base = '/'
  return {
    name: 'route-preload',
    apply: 'build',
    configResolved(config) { base = config.base },
    transformIndexHtml: {
      order: 'post',
      handler(html, ctx) {
        const bundle = ctx.bundle as Rollup.OutputBundle | undefined
        if (!bundle) return html
        const chunks = Object.values(bundle).filter((c): c is Rollup.OutputChunk => c.type === 'chunk')
        const byFile = new Map(chunks.map((c) => [c.fileName, c]))
        const map: Record<string, string[]> = {}
        for (const [route, mod] of Object.entries(ROUTES)) {
          const chunk = chunks.find((c) => c.facadeModuleId?.replaceAll('\\', '/').endsWith('/' + mod))
          if (!chunk) { console.warn(`route-preload: no chunk for ${route} (${mod}); update ROUTES in vite.config.ts`); continue }
          const files = new Set<string>()
          const visit = (c: Rollup.OutputChunk) => {
            if (c.isEntry || files.has(c.fileName)) return
            files.add(c.fileName)
            c.imports.forEach((f) => { const d = byFile.get(f); if (d) visit(d) })
          }
          visit(chunk)
          map[route] = [...files].map((f) => base + f)
        }
        const code = `(function(){var r=${JSON.stringify(map)},h=location.hash.slice(1);for(var k in r)if(h===k||h.indexOf(k+'/')===0)r[k].forEach(function(u){var l=document.createElement('link');l.rel='modulepreload';l.href=u;document.head.appendChild(l)})})()`
        return afterCharset(html, `<script>${code}</script>`)
      },
    },
  }
}

export default defineConfig({
  plugins: [react(), tailwindcss(), seoFiles(), designFonts(), routePreload()],
  resolve: { alias: { '@': fileURLToPath(new URL('./src', import.meta.url)) } },
})
